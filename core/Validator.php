class Validator
{
    private array $errors = [];
    private array $clean  = [];

    public function validate(array $input, array $rules): bool
    {
        foreach ($rules as $field => $rule) {
            $value = $input[$field] ?? null;

            // Reject arrays/objects (e.g. ?name[]=x) – only scalars allowed
            if ($value !== null && !is_scalar($value)) {
                $this->errors[$field] = 'Invalid input.';
                continue;
            }

            $value = is_string($value) ? trim($value) : $value;

            // Required / optional
            if ($value === null || $value === '') {
                if (!empty($rule['required'])) {
                    $this->errors[$field] = 'This field is required.';
                }
                continue;
            }

            // 1. Data type
            switch ($rule['type'] ?? 'string') {
                case 'int':
                    $value = filter_var($value, FILTER_VALIDATE_INT);
                    if ($value === false) {
                        $this->errors[$field] = 'Must be a whole number.';
                        continue 2;
                    }
                    if ((isset($rule['min']) && $value < $rule['min']) ||
                        (isset($rule['max']) && $value > $rule['max'])) {
                        $this->errors[$field] = 'Number out of range.';
                        continue 2;
                    }
                    break;

                case 'email':
                    if (filter_var($value, FILTER_VALIDATE_EMAIL) === false) {
                        $this->errors[$field] = 'Invalid email address.';
                        continue 2;
                    }
                    break;

                default: // string
                    $value = (string) $value;
            }

            // 2. Length (for strings/emails)
            // Assisted by VSCode Copilot
            if (is_string($value)) {
                $len = mb_strlen($value, 'UTF-8');
                if ((isset($rule['min']) && $len < $rule['min']) ||
                    (isset($rule['max']) && $len > $rule['max'])) {
                    if (isset($rule['min'], $rule['max'])) {
                        $this->errors[$field] = "Length must be between {$rule['min']} and {$rule['max']} characters.";
                    } elseif (isset($rule['min'])) {
                        $this->errors[$field] = "Must be at least {$rule['min']} characters.";
                    } else {
                        $this->errors[$field] = "Must be no more than {$rule['max']} characters.";
                    }
                    continue;
                }
            }

            // 3. Allowed characters (whitelist regex)
            if (isset($rule['pattern']) && !preg_match($rule['pattern'], (string) $value)) {
                $this->errors[$field] = 'Contains invalid characters.';
                continue;
            }

            // 4. Custom patterns with messages (for password complexity, etc.)
            if (isset($rule['patterns'])) {
                foreach ($rule['patterns'] as [$regex, $message]) {
                    if (!preg_match($regex, (string) $value)) {
                        $this->errors[$field] = $message;
                        continue 2; // stop at the first failed rule for this field
                    }
                }
            }

            $this->clean[$field] = $value;
        }

        return empty($this->errors);
    }

    public function errors(): array { return $this->errors; }
    public function clean(): array  { return $this->clean; }
}